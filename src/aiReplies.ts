// 特殊：還在👀我嗎（亞綸微信账号）已注销，不回复
export const BANNED = ["還在👀我嗎"];

export function aiReply(name: string, input: string): string {
  if (BANNED.includes(name)) return "「還在👀我嗎」的賬戶已註銷，無法回覆";
  const lib = AI_REPLIES[name];
  if (!lib) return "";
  for (const g of lib) {
    if (g.k.length && g.k.some((k) => input.includes(k))) {
      return g.r[Math.floor(Math.random() * g.r.length)];
    }
  }
  const def = lib.find((g) => g.k.length === 0);
  return def ? def.r[Math.floor(Math.random() * def.r.length)] : "";
}
